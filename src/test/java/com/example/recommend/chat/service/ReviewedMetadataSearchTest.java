package com.example.recommend.chat.service;

import com.example.recommend.chat.client.*;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import tools.jackson.databind.json.JsonMapper;
import javax.sql.DataSource;
import java.nio.charset.StandardCharsets;
import java.util.*;
import static com.example.recommend.chat.client.RecommendationConstraint.Kind.*;
import static org.junit.jupiter.api.Assertions.*;

/** Actual pinned public hints, synthetic H2 catalog and events. No provider/service DB. */
@DataJpaTest(showSql = false, properties = {"spring.jpa.hibernate.ddl-auto=create-drop", "spring.jpa.database-platform=org.hibernate.dialect.H2Dialect"})
@Import({CatalogRetriever.class, ReviewedMetadataSearch.class, CatalogToolService.class, ChatInteractionReader.class})
public class ReviewedMetadataSearchTest {
    @Autowired DataSource source;
    @Autowired EntityManager em;
    @Autowired CatalogRetriever retriever;
    @Autowired ReviewedMetadataSearch metadata;
    @Autowired CatalogToolService tools;
    JdbcTemplate jdbc;
    String payload, title, overview;
    static final JsonMapper JSON = JsonMapper.builder().build();

    @BeforeEach void setup() throws Exception {
        jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE TABLE IF NOT EXISTS catalog_metadata_search_events(event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_sha VARCHAR(64),previous_sha VARCHAR(64),enabled TINYINT,release_sha VARCHAR(64),search_sha VARCHAR(64),payload CLOB,event_body CLOB)");
        jdbc.update("DELETE FROM catalog_metadata_search_events");
        try (var stream = getClass().getResourceAsStream("/catalog/metadata-search-v1.json")) { payload = new String(stream.readAllBytes(), StandardCharsets.UTF_8); }
        var work = JSON.readTree(payload).get("works").get(0);
        assertEquals(45, work.get("content_id").asLong()); title = work.get("title").asString(); overview = work.get("overview").asString();
        jdbc.update("INSERT INTO contents(id,type,title,overview,genres,rating,view_count,runtime_minutes) VALUES(45,'MOVIE',?,?,'animation',1,0,90)", title, overview);
        for (int i=1000; i<1020; i++) jdbc.update("INSERT INTO contents(id,type,title,overview,genres,rating,view_count) VALUES(?,'MOVIE',?,'ordinary catalog plot','drama',10,0)", i, "baseline "+i);
    }

    String event(int enabled) {
        String previous = jdbc.query("SELECT event_sha FROM catalog_metadata_search_events ORDER BY event_id DESC LIMIT 1", (rs,i)->rs.getString(1)).stream().findFirst().orElse(null);
        var body = new TreeMap<String,Object>(); body.put("policy", ReviewedMetadataSearch.POLICY); body.put("previous_sha",previous);
        body.put("enabled",enabled); body.put("release_sha", ReviewedMetadataSearch.RELEASE); body.put("search_sha",ReviewedMetadataSearch.SEARCH_SHA);
        body.put("reason","Synthetic discovery switch"); body.put("actor","CODEX_DECLARED_NOT_AUTHENTICATED");body.put("declared_at","2026-11-26T14:00:00+00:00");
        String text = JSON.writeValueAsString(body), sha = ReviewedMetadataSearch.sha(text.getBytes(StandardCharsets.UTF_8));
        jdbc.update("INSERT INTO catalog_metadata_search_events(event_sha,previous_sha,enabled,release_sha,search_sha,payload,event_body) VALUES(?,?,?,?,?,?,?)",
                sha,previous,enabled,ReviewedMetadataSearch.RELEASE,ReviewedMetadataSearch.SEARCH_SHA,payload,text);
        return sha;
    }
    List<CatalogCandidate> find(String question) { return retriever.retrieve(List.of(new AiMessage(AiMessage.Role.USER,question))); }
    List<CatalogCandidate> criteria(RecommendationConstraint... constraints) {
        return retriever.retrieve(List.of(new AiMessage(AiMessage.Role.USER,"fish 추천")),new RecommendationCriteria(List.of(constraints),Set.of(),Set.of(),false));
    }
    RecommendationConstraint c(RecommendationConstraint.Kind kind,String value,String... terms) { return new RecommendationConstraint(kind,value,value,List.of(terms)); }

    @Test void inactiveHintsDoNotChangeExistingDiscovery() {
        assertTrue(find("fish 추천").isEmpty()); assertEquals(12,find("baseline 추천").size());
        assertTrue(find("Finding Nemo 추천").isEmpty());
    }
    @Test void activeKeywordsAndWholeWorkAliasesFindRealIdsBeforeLimitAndNeverAlterFacts() {
        event(1);
        assertEquals(payload,jdbc.queryForObject("SELECT LEFT(payload,200001) FROM catalog_metadata_search_events",String.class));
        String body=jdbc.queryForObject("SELECT event_body FROM catalog_metadata_search_events",String.class);
        assertEquals(8,JSON.readTree(body).size());
        assertEquals(List.of(45L),metadata.search("fish",List.of("fish")).stream().map(h->h.work().id()).toList(),"Reader must observe active event");
        assertEquals(List.of(45L),find("fish 추천").stream().map(CatalogCandidate::id).toList());
        assertEquals(List.of(45L),find("Finding Nemo 추천").stream().map(CatalogCandidate::id).toList());
        assertEquals(45,criteria(c(MOOD,"curious","fish")).get(0).id());
        assertEquals(12,criteria(c(MOOD,"curious","fish")).size());
        var found=find("fish 추천").get(0); assertEquals(title,found.title());assertFalse(found.overview().contains("fish"));
        assertEquals(90,found.runtimeMinutes());
    }
    @Test void mediaRuntimeGenreAndTrustedIdFiltersCannotBeRelaxedByMetadata() {
        event(1);
        assertTrue(criteria(c(MEDIA,"TV")).stream().noneMatch(w->w.id()==45));
        assertTrue(criteria(c(MINUTES_MAX,"30")).stream().noneMatch(w->w.id()==45));
        assertTrue(criteria(c(GENRE_EXCLUDE,"animation")).stream().noneMatch(w->w.id()==45));
        var only=new RecommendationCriteria(List.of(c(MOOD,"curious","fish")),Set.of(1000L),Set.of(45L),false);
        assertEquals(List.of(1000L),retriever.retrieve(List.of(new AiMessage(AiMessage.Role.USER,"fish")),only).stream().map(CatalogCandidate::id).toList());
    }
    @Test void metadataCannotReplaceRequiredTopicOrPlotEvidence() {
        event(1);
        assertTrue(criteria(c(TOPIC,"fish","fish")).isEmpty());
        assertThrows(ChatException.class,()->new RecommendationCriteria(List.of(c(TOPIC,"fish","fish")),Set.of(),Set.of(),false)
                .validateTopicEvidence(new CatalogRationale(List.of(new CatalogRationale.Evidence(CatalogRationale.Field.OVERVIEW,overview)),"fish")));
    }
    @Test void aliasExclusionsBecomeTrustedIdsAndCannotBeReintroducedByTools() {
        event(1);
        var request = new RecommendationCriteria(List.of(c(TITLE_EXCLUDE,"Finding Nemo"),c(MOOD,"curious","fish")),Set.of(),Set.of(9999L),false);
        var scoped = retriever.withReviewedAliasExclusions(request);
        assertEquals(Set.of(45L,9999L),scoped.excludedIds());
        var found = retriever.retrieve(List.of(new AiMessage(AiMessage.Role.USER,"fish")),scoped);
        assertTrue(found.stream().noneMatch(w->w.id()==45));
        var session=tools.session(123,found,scoped);
        assertEquals("{\"found\":false}",session.execute("get_content","{\"contentId\":45}"));
        assertFalse(session.execute("search_catalog","{\"query\":\"Finding Nemo\"}").contains("\"id\":45"));
        event(0);
        assertEquals(Set.of(45L,9999L),retriever.withReviewedAliasExclusions(scoped).excludedIds());
    }
    @Test void withdrawalIsObservedOnNextRetrievalWithoutRestartOrCachedFallback() {
        event(1);assertFalse(find("fish 추천").isEmpty());event(0);
        assertTrue(find("fish 추천").isEmpty());assertEquals(12,find("baseline 추천").size());
        event(1);assertEquals(45,find("fish 추천").get(0).id());
    }
    @Test void changedOverviewTitleTypeAndReusedIdsInvalidateHintsExactly() {
        event(1);
        jdbc.update("UPDATE contents SET overview=? WHERE id=45",overview+" ");assertTrue(find("fish 추천").isEmpty());
        jdbc.update("UPDATE contents SET overview=?,title=? WHERE id=45",overview,title+" ");assertTrue(find("fish 추천").isEmpty());
        jdbc.update("UPDATE contents SET title=?,type='movie' WHERE id=45",title);assertTrue(find("fish 추천").isEmpty());
        jdbc.update("UPDATE contents SET type='MOVIE' WHERE id=45");assertFalse(find("fish 추천").isEmpty());
        jdbc.update("DELETE FROM contents WHERE id=45");assertTrue(find("fish 추천").isEmpty());
    }
    @Test void missingInvalidOrTamperedLatestRecordFallsBackWithoutUsingOlderEvent() {
        event(1);jdbc.update("UPDATE catalog_metadata_search_events SET event_body='broken' WHERE enabled=1");
        assertTrue(find("fish 추천").isEmpty());assertEquals(12,find("baseline 추천").size());
        jdbc.update("DELETE FROM catalog_metadata_search_events");event(1);
        jdbc.update("UPDATE catalog_metadata_search_events SET payload=payload||' '");assertTrue(find("fish 추천").isEmpty());
        var absent=new ReviewedMetadataSearch(new DriverManagerDataSource("jdbc:h2:mem:absent_metadata_"+UUID.randomUUID(),"sa",""));
        assertTrue(absent.search("fish",List.of("fish")).isEmpty());
    }
    @Test void literalSearchAndEnglishWordBoundariesDoNotExecuteOrOvermatch() {
        event(1);
        assertTrue(find("fish%_' OR 1=1 --").stream().allMatch(w->w.id()==45 || w.title().startsWith("baseline")));
        assertTrue(metadata.search("award",List.of("award")).isEmpty());
        assertTrue(metadata.search("Finding Nemo 2",List.of()).stream().anyMatch(h->h.work().id()==45));
        assertTrue(metadata.search("Finding",List.of()).isEmpty());
        assertEquals(21,jdbc.queryForObject("SELECT COUNT(*) FROM contents",Integer.class));
    }
}
